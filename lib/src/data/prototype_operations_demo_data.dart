WorkRecord _paidInvoice({
  required String id,
  required String number,
  required String title,
  required String client,
  required String detail,
  required DateTime issuedOn,
  required double total,
  required String paymentMethod,
  required List<WorkLineItem> items,
}) => WorkRecord(
  id: id,
  kind: WorkRecordKind.invoice,
  number: number,
  title: title,
  client: client,
  detail: detail,
  pricing: WorkPricingModel.timeAndMaterials,
  createdOn: issuedOn,
  issuedOn: issuedOn,
  dueOn: issuedOn.add(const Duration(days: 30)),
  status: WorkRecordStatus.paid,
  items: items,
  paymentMethod: paymentMethod,
  terms: 'Payment due within 30 days.',
  total: total,
);

